◊section{Notebooks on Projective Geometry}

For this project, I'm primarily using Coxeter's ◊em{Projective Geometry} and Olive Whicher's ◊em{Projective Geometry: Creative Polarities in Space and Time}, switching between the two as I see fit. I also occasionally reference George Ballard Mathews' (quite old) textbook and Richard Southwell's series on YouTube.

As my study progresses, I'd like to bring in Lawrence Edwards' ◊em{Projective Geometry}. I originally wanted to use this as the primary text since his approach clearly has an eye towards biological applications but found that it was too advanced despite it not being particularly "textbooky". Other books worth mentioning are Louis Locher-Ernst's ◊em{Space and Counterspace}, Adams' and Whicher's ◊em{The Plant between Sun and Earth}, and Whicher's ◊em{The Heart of the Matter: Discovering the Laws of Living Organisms}, all of which I hope to study at a later date.

